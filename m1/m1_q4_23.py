ip_address= '192.168.3.1'
ip_spl = ip_address.split('.')
bin_exp = ''
for num in ip_spl:
    bin_exp += bin(int(num))[2:] + '.'
print(bin_exp[:-1])
print(type(bin_exp))




"""
split()関数とは文字列を分割し、リストを返す関数です。
bin()関数とは整数を2進数に変換する関数です。
int()関数とは文字列を整数に変換する関数です。
スライスについて[2:]は、文字列の2番目のインデックスから最後までを取得することを意味します。つまり、bin()関数で得られる2進数表現の先頭に付く'0b'を取り除くために使用されています。
スライスについて[:-1]は、文字列の最後のインデックスを除いた部分を取得することを意味します。つまり、最後のドットを取り除くために使用されています。
"""